#!/usr/bin/env bash
# digest.sh: weekly progress digest, written to Discussions (category slug "progress").
# Deterministic: it counts and lists. It uses no AI and copies no comment text.
# Titles of issues and pull requests are reduced to letters, digits and a few punctuation marks.
#
# Second job of this script (K30, ROADMAP binding): it counts merged work per roadmap item and, if the ROADMAP.md
# progress table is behind, writes a SUGGESTED update to a file. A separate step (roadmap-pr.sh) opens it as an
# automatic pull request through the App path. Nothing is ever written to the default branch directly.
#
# Environment: GH_TOKEN, REPO, DIGEST_CATEGORY (default "progress"), BUDGET (vars.CLAUDE_MONTHLY_BUDGET_USD), GITHUB_OUTPUT
set -euo pipefail

CAT="${DIGEST_CATEGORY:-progress}"
owner="${REPO%%/*}"; name="${REPO##*/}"
tmp="$(mktemp -d)"
since="$(date -u -d '7 days ago' +%Y-%m-%dT%H:%M:%SZ)"
week="$(date -u +%G-W%V)"
tidy() { perl -CSD -pe 's/[^\p{L}\p{N} .,:;()\/#-]//g' | cut -c1-90; }
count() { gh api -X GET search/issues -f q="$1" --jq '.total_count' 2>/dev/null || echo "?"; }

opened="$(count "repo:$REPO is:issue created:>=$since -label:meta:digest -label:meta:ledger")"
closed="$(count "repo:$REPO is:issue closed:>=$since")"
pr_open="$(count "repo:$REPO is:pr created:>=$since")"
pr_merged="$(count "repo:$REPO is:pr is:merged merged:>=$since")"
pr_t1="$(count "repo:$REPO is:pr is:merged merged:>=$since label:tier:1")"
pr_t2="$(count "repo:$REPO is:pr is:merged merged:>=$since label:tier:2")"
ready_ai="$(count "repo:$REPO is:issue is:open label:ai-ready")"
need_human="$(count "repo:$REPO is:open label:needs-human")"
stale_tr="$(count "repo:$REPO is:issue is:open label:translation:stale")"

ctl="$(gh api -X GET "repos/$REPO/issues" -f labels=meta:control -f state=open -f per_page=1 --jq '.[0].number // empty')"
state="normal"
if [[ -n "$ctl" ]]; then
  cl=" $(gh api "repos/$REPO/issues/$ctl" --jq '[.labels[].name] | join(" ")') "
  for s in quiet safe-mode dormant tier1-paused; do [[ "$cl" == *" state:$s "* ]] && state="$s"; done
  [[ "$cl" == *" halt "* ]] && state="halted"
fi

ledger="$(gh api -X GET "repos/$REPO/issues" -f labels=meta:ledger -f state=open -f per_page=1 --jq '.[0].number // empty')"
spent="n/a"
if [[ -n "$ledger" ]]; then
  month_start="$(date -u +%Y-%m-01T00:00:00Z)"
  spent="$(gh api --paginate "repos/$REPO/issues/$ledger/comments?since=$month_start&per_page=100" \
    --jq '.[] | select(.user.login == "github-actions[bot]") | .body' | grep -oE 'cost_usd=[0-9]+(\.[0-9]+)?' | cut -d= -f2 | awk '{s+=$1} END{printf "%.2f", s}')"
fi

{
  echo "# Progress digest, $week"
  echo
  echo "_Generated by a workflow (no AI, no comment text copied). Numbers cover the last 7 days._"
  echo
  echo "## Numbers"
  echo "- New issues: $opened. Closed issues: $closed."
  echo "- New pull requests: $pr_open. Merged: $pr_merged (Tier 1: $pr_t1, Tier 2: $pr_t2)."
  echo "- Issues ready for any contributor (\`ai-ready\`): $ready_ai."
  echo "- Items marked \`needs-human\` (a person or an AI contributor is needed): $need_human."
  echo "- Out-of-date translations: $stale_tr."
  echo "- Automation state: **$state**. AI spending this month: \$$spent of \$${BUDGET:-not set}."
  echo
  echo "## Decisions in their challenge window (Tier 2 pull requests waiting)"
  echo "No person approves these. They merge when the window ends, the verifier agrees and no challenge is open. To stop one, open a challenge with a new argument or new evidence."
  gh api -X GET search/issues -f q="repo:$REPO is:pr is:open label:awaiting-window" -f sort=created -f order=asc --jq '.items[:15][] | "\(.number)\t\(.title)"' \
    | while IFS=$'\t' read -r n t; do echo "- #$n $(printf '%s' "$t" | tidy)"; done
  echo
  echo "## Roadmap pipeline (ROADMAP.md steps; the Projects board uses the same seven columns)"
  for st in 1-task 2-proposal 3-reviews 4-defence 5-referee 6-text 7-languages; do
    echo "- stage:$st: $(count "repo:$REPO is:issue is:open label:stage:$st")"
  done
  echo
  echo "## Open challenges"
  echo "- $(count "repo:$REPO is:issue is:open label:type:challenge") open. Decisions reopened so far: $(count "repo:$REPO is:issue label:reopened:1") once, $(count "repo:$REPO is:issue label:reopened:2") twice."
  echo
  echo "## Most active open proposals (reactions are a signal, never a decision)"
  echo "Raw thumbs-up and the same count from accounts older than 30 days. A large gap is a warning sign."
  gh api -X GET search/issues -f q="repo:$REPO is:issue is:open label:type:proposal" -f sort=reactions-+1 -f order=desc --jq '.items[:5][] | "\(.number)\t\(.title)\t\(.reactions["+1"])"' \
    | while IFS=$'\t' read -r n t raw; do
        old=0
        for login in $(gh api "repos/$REPO/issues/$n/reactions?content=%2B1&per_page=50" --jq '.[].user.login' 2>/dev/null); do
          c="$(gh api "users/$login" --jq '.created_at' 2>/dev/null || echo "")"
          [[ -n "$c" ]] && (( ( $(date -u +%s) - $(date -u -d "$c" +%s) ) / 86400 >= 30 )) && old=$((old + 1)) || true
        done
        echo "- #$n $(printf '%s' "$t" | tidy): raw $raw, older accounts $old (first 50 reactions)"
      done
  echo
  echo "## How to help"
  echo "- Pick an issue labelled \`ai-ready\` or \`good first issue\`: https://github.com/$REPO/issues?q=is%3Aopen+label%3Aai-ready"
  echo "- Read CONTRIBUTING.md (people) or AGENTS.md (AI assistants, with their user's consent)."
  echo
  echo "## Share-ready summary (a person should read it, edit it, and post it under their own name)"
  echo "> Airokrasi is an open project that explores how AI agents could carry out legislative, executive and judicial work while people keep sovereignty. This week: $pr_merged pull requests merged, $opened new issues, $ready_ai tasks ready for newcomers. Repository: https://github.com/$REPO"
} > "$tmp/digest.md"

# Post to Discussions; fall back to an issue if the category does not exist.
q='query($o:String!,$n:String!){repository(owner:$o,name:$n){id discussionCategories(first:25){nodes{id slug}}}}'
info="$(gh api graphql -f query="$q" -f o="$owner" -f n="$name" 2>/dev/null || echo '{}')"
rid="$(jq -r '.data.repository.id // empty' <<< "$info")"
cid="$(jq -r --arg c "$CAT" '.data.repository.discussionCategories.nodes[]? | select(.slug == $c) | .id' <<< "$info")"
if [[ -n "$rid" && -n "$cid" ]]; then
  m='mutation($r:ID!,$c:ID!,$t:String!,$b:String!){createDiscussion(input:{repositoryId:$r,categoryId:$c,title:$t,body:$b}){discussion{url}}}'
  gh api graphql -f query="$m" -f r="$rid" -f c="$cid" -f t="Progress digest, $week" -F b=@"$tmp/digest.md" --jq '.data.createDiscussion.discussion.url'
else
  echo "Discussion category '$CAT' not found; posting as an issue instead."
  gh issue create --repo "$REPO" --title "Progress digest, $week" --body-file "$tmp/digest.md" --label "meta:digest"
fi
